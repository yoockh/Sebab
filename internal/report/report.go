// Package report renders a check as a Markdown snippet for bug reports and chat
// ("Copy diagnosis"). Output is always passed through the redactor.
package report

import (
	"fmt"
	"strings"
	"time"

	"github.com/yoockh/sebab/internal/event"
	"github.com/yoockh/sebab/internal/secret"
)

const stamp = "2006-01-02 15:04:05 MST"

// Markdown renders one check event. version names the engine that produced it.
func Markdown(c event.Check, version string, red *secret.Redactor) string {
	var b strings.Builder
	row := func(k, v string) {
		if v != "" {
			fmt.Fprintf(&b, "| %s | %s |\n", k, escape(v))
		}
	}
	fmt.Fprintf(&b, "### Sebab diagnosis: %s\n\n", escape(c.Monitor.Name))
	b.WriteString("| Field | Value |\n|---|---|\n")
	row("Monitor", fmt.Sprintf("%s (%s)", c.Monitor.ID, c.Monitor.Kind))
	row("Target", secret.RedactURL(c.Monitor.Target))
	status := strings.ToUpper(string(c.Status))
	if c.Since != nil {
		status += " since " + c.Since.Time().UTC().Format(stamp)
	}
	row("Status", status)
	if c.Cause != nil {
		row("Cause", fmt.Sprintf("%s (%s layer, %s side)", c.Cause.Code, c.Cause.Layer, sideText(c.Side)))
		row("Summary", c.Cause.Summary)
		row("Hint", c.Cause.Hint)
	}
	row("Timings", Timings(c.Timings, c.Cause))
	if d := c.Details; d != nil {
		if d.HTTPStatus != 0 {
			row("HTTP status", fmt.Sprintf("%d", d.HTTPStatus))
		}
		row("Address", strings.TrimSpace(d.Address+" "+d.Family))
		if d.TLSNotAfter != nil {
			row("Certificate valid until", d.TLSNotAfter.Time().UTC().Format(stamp))
		}
	}
	if c.Monitor.InsecureTLS {
		row("Note", "TLS verification is disabled for this monitor (insecure_tls)")
	}
	row("Checked at", c.TS.Time().UTC().Format(stamp))
	fmt.Fprintf(&b, "\n_Generated by sebab %s at %s._\n", version, time.Now().UTC().Format(stamp))
	return red.Scrub(b.String())
}

func sideText(s event.Side) string {
	switch s {
	case event.SideYours:
		return "your"
	case event.SideTheirs:
		return "their"
	default:
		return "unknown"
	}
}

// Timings renders "DNS 12 ms, TCP 38 ms, TLS failed, total 51 ms".
func Timings(t event.Timings, cause *event.Cause) string {
	var parts []string
	add := func(name string, v *int64, layer event.Layer) {
		switch {
		case v != nil:
			parts = append(parts, fmt.Sprintf("%s %d ms", name, *v))
		case cause != nil && cause.Layer == layer:
			parts = append(parts, name+" failed")
		}
	}
	add("DNS", t.DNS, event.LayerDNS)
	add("TCP", t.TCP, event.LayerTCP)
	add("TLS", t.TLS, event.LayerTLS)
	add("TTFB", t.TTFB, event.LayerHTTP)
	if t.Total != nil {
		parts = append(parts, fmt.Sprintf("total %d ms", *t.Total))
	}
	return strings.Join(parts, ", ")
}

func escape(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ").Replace(s)
}
