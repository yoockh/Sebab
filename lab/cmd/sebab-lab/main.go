// Command sebab-lab runs the failure lab on loopback for manual testing. It
// prints a config whose monitors each induce one cause code, and the commands
// to point the real sebab binary at the lab's DNS server.
package main

import (
	"flag"
	"fmt"
	"os"
	"os/signal"
	"path/filepath"
	"strings"
	"syscall"

	"github.com/yoockh/sebab/lab"
)

func main() {
	dns := flag.String("dns", "127.0.0.1:15353", "address for the lab DNS server")
	base := flag.Int("base-port", 18080, "first of 9 consecutive loopback ports")
	out := flag.String("out", "lab/out", "directory for ca.pem and config.toml")
	flag.Parse()
	ports := make([]int, 9)
	for i := range ports {
		ports[i] = *base + i
	}
	l, err := lab.Start(lab.Options{DNSAddr: *dns, Ports: ports})
	if err != nil {
		fmt.Fprintln(os.Stderr, "sebab-lab:", err)
		os.Exit(1)
	}
	defer l.Close()
	if err := os.MkdirAll(*out, 0o700); err != nil {
		fmt.Fprintln(os.Stderr, "sebab-lab:", err)
		os.Exit(1)
	}
	caPath, _ := filepath.Abs(filepath.Join(*out, "ca.pem"))
	if err := os.WriteFile(caPath, l.Certs.CAPEM, 0o600); err != nil {
		fmt.Fprintln(os.Stderr, "sebab-lab:", err)
		os.Exit(1)
	}
	cfgPath, _ := filepath.Abs(filepath.Join(*out, "config.toml"))
	if err := os.WriteFile(cfgPath, []byte(Config(l, caPath)), 0o600); err != nil {
		fmt.Fprintln(os.Stderr, "sebab-lab:", err)
		os.Exit(1)
	}
	fmt.Printf(`Sebab failure lab is running (Ctrl+C to stop).

  DNS server : %s   (*.lab.test, see lab/dns.go for the special names)
  Lab CA     : %s
  Config     : %s

Try it with the real binary (no system changes, everything on loopback):

  export SEBAB_LAB_DNS=%s SEBAB_CONFIG=%s   # lab DNS + loopback canary
  ./bin/sebab check http://app.lab.test:%d/status/502
  ./bin/sebab check --ca-file %s https://app.lab.test:%d/ok
  ./bin/sebab watch --embedded

TEST-NET-1 (192.0.2.1, blackhole.lab.test) is not routed on most machines, so
its result depends on your network: TCP_TIMEOUT where packets are dropped,
TCP_UNREACHABLE where the kernel rejects the route.
`, *dns, caPath, cfgPath, *dns, cfgPath, l.HTTPPort, caPath, l.TLSPorts[lab.TLSExpired])
	sig := make(chan os.Signal, 1)
	signal.Notify(sig, os.Interrupt, syscall.SIGTERM)
	<-sig
}

// Config returns a sebab config with one monitor per lab failure mode.
func Config(l *lab.Lab, caPath string) string {
	var b strings.Builder
	b.WriteString("# Generated by sebab-lab. One monitor per cause code.\n[defaults]\ninterval = \"30s\"\ntimeout = \"5s\"\n")
	b.WriteString("canary = [\"tcp://127.0.0.1:" + fmt.Sprint(l.HTTPPort) + "\"]\ndns_canary = [\"canary.lab.test\"]\n")
	mon := func(id, name, field, value, extra string) {
		fmt.Fprintf(&b, "\n[[monitor]]\nid = %q\nname = %q\n%s = %q\n%s", id, name, field, value, extra)
	}
	h := func(path string) string { return l.HTTPURL("app.lab.test", path) }
	t := func(server, path string) string { return l.TLSURL(server, "app.lab.test", path) }
	ca := fmt.Sprintf("ca_file = %q\n", caPath)
	mon("ok", "Healthy", "url", h("/ok"), "")
	mon("nxdomain", "DNS NXDOMAIN", "url", l.HTTPURL(lab.NameNXDomain, "/"), "")
	mon("servfail", "DNS SERVFAIL", "url", l.HTTPURL(lab.NameServFail, "/"), "")
	mon("dns-timeout", "DNS timeout", "url", l.HTTPURL(lab.NameTimeout, "/"), "")
	mon("noaddr", "DNS no address", "url", l.HTTPURL(lab.NameNoAddress, "/"), "")
	mon("refused", "TCP refused", "target", fmt.Sprintf("tcp://db.lab.test:%d", l.RefusedPort), "")
	mon("blackhole", "TCP blackhole (TEST-NET-1)", "target", lab.NameBlackhole+":5432", "")
	mon("expired", "TLS expired", "url", t(lab.TLSExpired, "/ok"), ca)
	mon("notyet", "TLS not yet valid", "url", t(lab.TLSNotYet, "/ok"), ca)
	mon("wronghost", "TLS wrong host", "url", t(lab.TLSWrongHost, "/ok"), ca)
	mon("selfsigned", "TLS self-signed", "url", t(lab.TLSSelfSign, "/ok"), "")
	mon("expiring", "TLS expiring soon", "url", t(lab.TLSSoon, "/ok"), ca)
	mon("handshake", "TLS handshake failure", "url", fmt.Sprintf("https://app.lab.test:%d/", l.HandshakePort), "")
	mon("http-401", "HTTP 401", "url", h("/status/401"), "")
	mon("http-502", "HTTP 502", "url", h("/status/502"), "")
	mon("http-503", "HTTP 503", "url", h("/status/503"), "")
	mon("http-500", "HTTP 500", "url", h("/status/500"), "")
	mon("http-404", "HTTP 404", "url", h("/status/404"), "")
	mon("http-429", "HTTP 429", "url", h("/status/429"), "")
	mon("slow", "HTTP slow", "url", h("/slow?ms=3000"), "")
	mon("hang", "HTTP timeout", "url", h("/hang"), "")
	mon("wrong-status", "HTTP wrong status", "url", h("/ok"), "expect_status = [204]\n")
	mon("redirect-away", "HTTP unexpected redirect", "url", h("/away"), "")
	mon("redirect-loop", "HTTP redirect loop", "url", h("/loop"), "")
	mon("vpn", "Needs VPN sebab0", "url", h("/ok"), "requires_vpn = { interface = \"sebab0\" }\n")
	return b.String()
}
